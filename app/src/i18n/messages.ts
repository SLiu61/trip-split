export const messages: Record<Lang, Record<MessageKey, string>> = { en, zh };

export type TFunc = (key: MessageKey, vars?: Record<string, string | number>) => string;

export function makeT(lang: Lang): TFunc {
  const dict = messages[lang];
  return (key, vars) => {
    let s = dict[key] ?? messages.en[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
    return s;
  };
}
